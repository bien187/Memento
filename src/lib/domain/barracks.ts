export function barracksForFunction(functionId: string | null) {
  return (functionBarracks[functionId ?? ""] ?? [])
    .map((id) => barracks.find((location) => location.id === id)!)
    .filter(Boolean);
}
export function suggestedBarracks(
  functionId: string | null,
  currentId?: string | null,
): string | null {
  const suggestions = barracksForFunction(functionId);
  return (
    suggestions.find((location) => location.id === currentId)?.id ??
    suggestions[0]?.id ??
    null
  );
}
export function barracksLabel(id?: string | null) {
  const location = barracks.find((location) => location.id === id);
  return location ? `${location.name} (${location.canton})` : "Noch offen";
}
